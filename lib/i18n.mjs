export function translate(locale, key, values = {}) {
  const text = messages[normalizeLocale(locale)][key];
  if (typeof text !== 'string') throw new Error(`Missing translation key: ${key}`);
  return text.replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, name) => {
    if (!Object.hasOwn(values, name)) throw new Error(`Missing translation value: ${key}.${name}`);
    return String(values[name]);
  });
}

export function translationCatalogs() {
  return messages;
}

export function candidateDescription({ tier, tools, live, inScope }, locale = 'en') {
  return [
    translate(locale, 'candidate.tier', { tier }),
    translate(locale, tools ? 'candidate.tools' : 'candidate.noTools'),
    live ? null : translate(locale, 'candidate.unauthenticated'),
    inScope ? null : translate(locale, 'candidate.outsideScope'),
  ].filter(Boolean).join(' · ');
}

export function localizedHelpLines(locale, lines) {
  return lines.map((line, index) => {
    if (index === 0) {
      const split = line.indexOf(' — ');
      return split < 0 ? translate(locale, 'help.header') : `${line.slice(0, split + 3)}${translate(locale, 'help.header')}`;
    }
    const action = line.match(/^\/economist\s+([^\s]+)/)?.[1];
    const separator = line.indexOf(' — ');
    if (!action || separator < 0 || !Object.hasOwn(messages[normalizeLocale(locale)], `help.${action}`)) return line;
    const prefix = line.slice(0, separator + 3).replace(
      'write the global config instead',
      translate(locale, 'help.globalFlag'),
    );
    return `${prefix}${translate(locale, `help.${action}`)}`;
  });
}

/** Read only the locale field from the trusted project's local extension config. */
export function loadProjectLocale(root, trusted) {
  if (!trusted || !root) return { locale: 'en', hasStoredValue: false, invalid: false };
  try {
    const path = join(root, '.pi', 'pi-suite.yaml');
    if (statSync(path).size > 1_000_000) return { locale: 'en', hasStoredValue: false, invalid: true };
    const source = readFileSync(path, 'utf8');
    const document = parseDocument(source);
    if (document.errors.length) return { locale: 'en', hasStoredValue: false, invalid: true };
    const value = document.toJS()?.modelEconomist?.locale;
    if (value == null) return { locale: 'en', hasStoredValue: false, invalid: false };
    return {
      locale: normalizeLocale(value),
      hasStoredValue: true,
      invalid: value !== 'en' && value !== 'pt-BR',
    };
  } catch (error) {
    if (error?.code === 'ENOENT') return { locale: 'en', hasStoredValue: false, invalid: false };
    return { locale: 'en', hasStoredValue: false, invalid: true };
  }
}
